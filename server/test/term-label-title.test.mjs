import assert from 'node:assert/strict';
import { titleLabel } from '../src/term-label.js';
assert.equal(titleLabel('terminal - Swarm edits'), 'Terminal - Swarm edits');
assert.equal(titleLabel('one two three four five six'), 'One two three four');
assert.equal(titleLabel('  login   error fix '), 'Login error fix');
assert.equal(titleLabel(''), '');
console.log('Terminal title limits passed');
const { labelRequest } = await import('../src/term-label.js');
assert.equal(labelRequest(undefined), null);
assert.equal(labelRequest({}), null);
assert.deepEqual(labelRequest({ sid: 's1', tmux: 'stack-term-a', prompt: '  Fix Swarm titles  ' }), { sid: 's1', tmux: 'stack-term-a', prompt: 'Fix Swarm titles' });
assert.throws(() => labelRequest({ prompt: 'Do something' }), /identity/);
assert.throws(() => labelRequest({ sid: 's1', prompt: ' ' }), /prompt/);
assert.equal(labelRequest({ tmux: 'stack-term-a', prompt: 'x'.repeat(9000) }).prompt.length, 8000);
